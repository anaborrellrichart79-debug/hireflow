const storedLang = localStorage.getItem(STORAGE_KEY);
let currentLang = SUPPORTED_LANGS.includes(storedLang) ? storedLang : DEFAULT_LANG;

const listeners = [];

export const getLang = () => currentLang;

export const getLangName = (lang) => LANG_NAMES[lang] || lang;

export const setLang = (lang) => {
    if (!SUPPORTED_LANGS.includes(lang) || lang === currentLang) {
        return;
    }
    currentLang = lang;
    localStorage.setItem(STORAGE_KEY, lang);
    listeners.forEach((fn) => fn(lang));
};

export const onLangChange = (fn) => {
    listeners.push(fn);
};

export const t = (key) => {
    return dictionaries[currentLang]?.[key]
        ?? dictionaries[DEFAULT_LANG]?.[key]
        ?? key;
};

// Frases de la mascota: mezcla de consejos y frases graciosas, con un banco
// neutro (sin sesión / cualquier rol) más un banco específico según role.
const MASCOT_NEUTRAL_KEYS = ["mascot.neutral1", "mascot.neutral2", "mascot.neutral3", "mascot.neutral4", "mascot.neutral5"];
const MASCOT_CANDIDATE_KEYS = ["mascot.candidate1", "mascot.candidate2", "mascot.candidate3", "mascot.candidate4", "mascot.candidate5"];
const MASCOT_RECRUITER_KEYS = ["mascot.recruiter1", "mascot.recruiter2", "mascot.recruiter3", "mascot.recruiter4", "mascot.recruiter5"];

export const getMascotPhrases = (role) => {
    const roleKeys = role === "recruiter" ? MASCOT_RECRUITER_KEYS : role === "candidate" ? MASCOT_CANDIDATE_KEYS : [];
    return [...roleKeys, ...MASCOT_NEUTRAL_KEYS].map((key) => t(key));
};
